const SUBJECT_HINT = 'Предмет не указан — определи его по условию.';

export function buildContext({ subject, task, mode }) {
  const lines = [];
  lines.push('<context>');
  lines.push(`Предмет: ${subject ? subject.name : SUBJECT_HINT}`);
  lines.push(`Формат: ${mode === 'olymp' ? 'олимпиада (ВсОШ / РСОШ)' : 'ЕГЭ'}`);
  if (task) {
    lines.push(`Задача: ${task.kind === 'ege' && task.n ? `линия КИМ №${task.n}, ` : ''}«${task.title}» (${task.level})`);
    lines.push('<task>');
    lines.push(task.statement);
    lines.push('</task>');
    lines.push('<reference>');
    if (task.answer) lines.push(`Верный ответ: ${task.answer}`);
    lines.push(task.full);
    lines.push('</reference>');
  }
  lines.push('</context>');
  return lines.join('\n');
}

export function actionText(action, { hintLevel, question } = {}) {
  if (action === 'hint') return `Дай подсказку №${hintLevel} к этой задаче. Только следующий шаг, без ответа.`;
  if (action === 'solution') return 'Покажи полное решение этой задачи со всеми объяснениями.';
  return question;
}
